   'Google Drive folder id that roots the QC job-documentation archive (folders per year/month/job). The Google service account must have edit access to it.')
ON CONFLICT (key) DO NOTHING;

-- ─── 8. Cron: Drive mirror worker + 14-day retention purge ───────────────────
DO $$
DECLARE
  v_job_id bigint;
  v_supabase_url text;
  v_service_role text;
BEGIN
  SELECT value INTO v_supabase_url FROM public.app_secrets WHERE key = 'SUPABASE_URL';
  IF v_supabase_url IS NULL OR length(v_supabase_url) = 0 THEN
    v_supabase_url := 'https://sxdraeptzuamsgjcvfeg.supabase.co';
  END IF;
  SELECT value INTO v_service_role FROM public.app_secrets WHERE key = 'SUPABASE_SERVICE_ROLE_KEY';

  SELECT jobid INTO v_job_id FROM cron.job WHERE jobname = 'qc-drive-mirror';
  IF v_job_id IS NOT NULL THEN PERFORM cron.unschedule('qc-drive-mirror'); END IF;
  PERFORM cron.schedule(
    'qc-drive-mirror',
    '*/10 * * * *',
    format(
      $cron$
        SELECT net.http_post(
          url := '%s/functions/v1/qc-drive-mirror',
          headers := jsonb_build_object(
            'Content-Type', 'application/json',
            'Authorization', 'Bearer ' || coalesce(%L::text, '')
          ),
          body := jsonb_build_object('source', 'pg_cron')
        );
      $cron$,
      v_supabase_url,
      v_service_role
    )
  );

  SELECT jobid INTO v_job_id FROM cron.job WHERE jobname = 'qc-retention-purge';
  IF v_job_id IS NOT NULL THEN PERFORM cron.unschedule('qc-retention-purge'); END IF;
  PERFORM cron.schedule(
    'qc-retention-purge',
    '30 8 * * *',
    format(
      $cron$
        SELECT net.http_post(
          url := '%s/functions/v1/qc-retention-purge',
          headers := jsonb_build_object(
            'Content-Type', 'application/json',
            'Authorization', 'Bearer ' || coalesce(%L::text, '')
          ),
          body := jsonb_build_object('source', 'pg_cron')
        );
      $cron$,
      v_supabase_url,
      v_service_role
    )
  );
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'Skipping QC cron scheduling: %', SQLERRM;
END $$;
