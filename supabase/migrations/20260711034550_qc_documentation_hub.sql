-- ─── 4. Auto-create documentation record when a booking completes ────────────
-- Fires on completion AND on later photo submissions (photos often land after
-- the status flip). Never overwrites a purged record's photo arrays.
CREATE OR REPLACE FUNCTION public.ensure_job_documentation()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_before jsonb;
  v_after jsonb;
  v_documented boolean;
BEGIN
  IF NEW.status IS DISTINCT FROM 'completed' THEN RETURN NEW; END IF;

  v_before := to_jsonb(coalesce(NEW.before_photos, '{}'::text[]));
  v_after  := to_jsonb(coalesce(NEW.after_photos,  '{}'::text[]));
  v_documented := jsonb_array_length(v_before) > 0 AND jsonb_array_length(v_after) > 0;

  INSERT INTO public.job_documentation (
    booking_id, job_id, booking_ref, client_name, client_email,
    service_type, service_date, address, before_photos, after_photos,
    photo_count, notes, completed_at, documented
  ) VALUES (
    NEW.id,
    NEW.job_id,
    CASE WHEN NEW.booking_number IS NOT NULL THEN 'NOV-' || lpad(NEW.booking_number::text, 5, '0') ELSE NULL END,
    nullif(btrim(coalesce(NEW.first_name,'') || ' ' || coalesce(NEW.last_name,'')), ''),
    NEW.email,
    NEW.service_type,
    NEW.service_date,
    nullif(btrim(concat_ws(', ', NEW.address, NEW.city, NEW.state) || ' ' || coalesce(NEW.zip_code,'')), ''),
    v_before,
    v_after,
    jsonb_array_length(v_before) + jsonb_array_length(v_after),
    nullif(btrim(concat_ws(E'\n', NEW.team_notes, NEW.issues_notes)), ''),
    coalesce(NEW.completed_at, now()),
    v_documented
  )
  ON CONFLICT (booking_id) DO UPDATE SET
    job_id        = coalesce(EXCLUDED.job_id, job_documentation.job_id),
    before_photos = CASE WHEN job_documentation.photos_purged_at IS NULL THEN EXCLUDED.before_photos ELSE job_documentation.before_photos END,
    after_photos  = CASE WHEN job_documentation.photos_purged_at IS NULL THEN EXCLUDED.after_photos  ELSE job_documentation.after_photos  END,
    photo_count   = CASE WHEN job_documentation.photos_purged_at IS NULL THEN EXCLUDED.photo_count   ELSE job_documentation.photo_count   END,
    documented    = CASE WHEN job_documentation.photos_purged_at IS NULL THEN EXCLUDED.documented    ELSE job_documentation.documented    END,
    notes         = coalesce(EXCLUDED.notes, job_documentation.notes),
    completed_at  = coalesce(job_documentation.completed_at, EXCLUDED.completed_at),
    -- New photos after a successful mirror → re-queue (worker dedupes by filename).
    mirror_status = CASE
      WHEN job_documentation.photos_purged_at IS NOT NULL THEN job_documentation.mirror_status
      WHEN job_documentation.mirror_status = 'mirrored'
        AND EXCLUDED.photo_count > job_documentation.photo_count THEN 'pending'
      ELSE job_documentation.mirror_status
    END,
    updated_at    = now();

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_ensure_job_documentation ON public.bookings;
CREATE TRIGGER trg_ensure_job_documentation
  AFTER INSERT OR UPDATE OF status, before_photos, after_photos ON public.bookings
  FOR EACH ROW EXECUTE FUNCTION public.ensure_job_documentation();

-- ─── 5. Backfill: completed bookings from the last 90 days ───────────────────
INSERT INTO public.job_documentation (
  booking_id, job_id, booking_ref, client_name, client_email, service_type,
  service_date, address, before_photos, after_photos, photo_count, notes,
  completed_at, documented
)
SELECT
  b.id, b.job_id,
  CASE WHEN b.booking_number IS NOT NULL THEN 'NOV-' || lpad(b.booking_number::text, 5, '0') END,
  nullif(btrim(coalesce(b.first_name,'') || ' ' || coalesce(b.last_name,'')), ''),
  b.email, b.service_type, b.service_date,
  nullif(btrim(concat_ws(', ', b.address, b.city, b.state) || ' ' || coalesce(b.zip_code,'')), ''),
  to_jsonb(coalesce(b.before_photos, '{}'::text[])),
  to_jsonb(coalesce(b.after_photos,  '{}'::text[])),
  coalesce(array_length(b.before_photos, 1), 0) + coalesce(array_length(b.after_photos, 1), 0),
  nullif(btrim(concat_ws(E'\n', b.team_notes, b.issues_notes)), ''),
  coalesce(b.completed_at, b.service_date::timestamptz),
  coalesce(array_length(b.before_photos, 1), 0) > 0 AND coalesce(array_length(b.after_photos, 1), 0) > 0
FROM public.bookings b
WHERE b.status = 'completed'
  AND coalesce(b.completed_at, b.service_date::timestamptz) > now() - interval '90 days'
ON CONFLICT (booking_id) DO NOTHING;

-- ─── 6. Discord alert routing for QC events ──────────────────────────────────
-- Unknown event types fall through notify_discord_on_event()'s ELSE branch
-- (generic bell + event summary), so routes alone are enough to wire alerts.
INSERT INTO public.discord_routes (event_type, webhook_key, role_keys) VALUES
  ('qc.issue.created',         'DISCORD_WEBHOOK_FLAG', ARRAY['DISCORD_ROLE_OPERATIONS','DISCORD_ROLE_RETENTION']),
  ('qc.issue.escalated',       'DISCORD_WEBHOOK_FLAG', ARRAY['DISCORD_ROLE_OPERATIONS','DISCORD_ROLE_RETENTION']),
  ('qc.documentation.failed',  'DISCORD_WEBHOOK_FLAG', ARRAY['DISCORD_ROLE_OPERATIONS'])
ON CONFLICT (event_type) DO UPDATE
  SET webhook_key = EXCLUDED.webhook_key, role_keys = EXCLUDED.role_keys, enabled = true;

