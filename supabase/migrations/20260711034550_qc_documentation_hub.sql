-- ─── QC & Job Documentation Hub ──────────────────────────────────────────────
--
-- Two connected capabilities:
--   1. Every completed job gets a durable documentation record (before/after
--      photos, checklist snapshot, notes, timestamps). Supabase is the source
--      of truth; each job is mirrored asynchronously to a structured Google
--      Drive folder with a generated completion-summary PDF (the dispute
--      packet). Photos live in Supabase for 14 days, then are purged — but
--      ONLY after the Drive mirror is confirmed.
--   2. QC issues (complaints, re-cleans, damage, no-shows, quality flags…)
--      are always tied to a job, carrying that job's documentation as
--      evidence, with a full lifecycle + audit trail. High/Critical issues
--      alert admin immediately through the existing Discord event routing.
--
-- Reuses: public.events + discord_routes (alerts), pg_cron + pg_net (workers),
-- is_admin_or_va() RLS, cleaner-job-photos bucket, job_checklists.

-- ─── 1. job_documentation — one durable record per completed booking ────────
CREATE TABLE IF NOT EXISTS public.job_documentation (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid NOT NULL UNIQUE REFERENCES public.bookings(id) ON DELETE CASCADE,
  job_id uuid,
  booking_ref text,
  client_name text,
  client_email text,
  service_type text,
  service_date date,
  address text,
  cleaner_names text,
  -- Snapshot of photo URLs at documentation time (source: bookings arrays).
  before_photos jsonb NOT NULL DEFAULT '[]'::jsonb,
  after_photos jsonb NOT NULL DEFAULT '[]'::jsonb,
  photo_count integer NOT NULL DEFAULT 0,
  -- Checklist snapshot captured by the mirror worker at documentation time.
  checklist_snapshot jsonb,
  checklist_progress_pct integer,
  notes text,
  completed_at timestamptz,
  -- "Documented" = has both before AND after photos. The compliance metric.
  documented boolean NOT NULL DEFAULT false,
  -- Google Drive mirror state machine. pending → mirroring → mirrored.
  -- Failures retry with backoff; photos are NEVER purged unless mirrored.
  mirror_status text NOT NULL DEFAULT 'pending'
    CHECK (mirror_status IN ('pending','mirroring','mirrored','failed','skipped')),
  mirror_attempts integer NOT NULL DEFAULT 0,
  mirror_last_error text,
  mirror_next_attempt_at timestamptz,
  mirrored_at timestamptz,
  drive_folder_id text,
  drive_folder_url text,
  drive_pdf_id text,
  drive_pdf_url text,
  drive_file_count integer NOT NULL DEFAULT 0,
  -- 14-day retention: set when Supabase copies were deleted (Drive keeps all).
  photos_purged_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS job_documentation_mirror_idx
  ON public.job_documentation (mirror_status, mirror_next_attempt_at);
CREATE INDEX IF NOT EXISTS job_documentation_purge_idx
  ON public.job_documentation (mirror_status, completed_at)
  WHERE photos_purged_at IS NULL;
CREATE INDEX IF NOT EXISTS job_documentation_booking_idx
  ON public.job_documentation (booking_id);
ALTER TABLE public.job_documentation ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='job_documentation' AND policyname='job_documentation_admin_all') THEN
    CREATE POLICY job_documentation_admin_all ON public.job_documentation FOR ALL TO authenticated
      USING (public.is_admin_or_va(auth.uid())) WITH CHECK (public.is_admin_or_va(auth.uid()));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='job_documentation' AND policyname='job_documentation_service_role') THEN
    CREATE POLICY job_documentation_service_role ON public.job_documentation FOR ALL TO service_role USING (true) WITH CHECK (true);
  END IF;
END$$;

-- ─── 2. qc_issues — every issue is tied to a job ─────────────────────────────
CREATE TABLE IF NOT EXISTS public.qc_issues (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  issue_number integer GENERATED BY DEFAULT AS IDENTITY,
  booking_id uuid NOT NULL REFERENCES public.bookings(id) ON DELETE CASCADE,
  job_id uuid,
  documentation_id uuid REFERENCES public.job_documentation(id) ON DELETE SET NULL,
  cleaner_id uuid,
  cleaner_name text,
  client_name text,
  client_email text,
  booking_ref text,
  issue_type text NOT NULL DEFAULT 'complaint'
    CHECK (issue_type IN ('complaint','reclean','damage','no_show','late','quality_flag','payment','other')),
  severity text NOT NULL DEFAULT 'medium'
    CHECK (severity IN ('low','medium','high','critical')),
  status text NOT NULL DEFAULT 'open'
    CHECK (status IN ('open','investigating','awaiting_customer','resolved','escalated')),
  title text NOT NULL,
  description text,
  reported_via text NOT NULL DEFAULT 'va'
    CHECK (reported_via IN ('va','admin','cleaner_field','system')),
  reported_by uuid,
  reported_by_name text,
  resolution_note text,
  resolution_photos jsonb NOT NULL DEFAULT '[]'::jsonb,
  resolved_at timestamptz,
  resolved_by uuid,
  resolved_by_name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS qc_issues_status_idx ON public.qc_issues (status, severity, created_at DESC);
CREATE INDEX IF NOT EXISTS qc_issues_booking_idx ON public.qc_issues (booking_id);
CREATE INDEX IF NOT EXISTS qc_issues_cleaner_idx ON public.qc_issues (cleaner_id, created_at DESC);
ALTER TABLE public.qc_issues ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='qc_issues' AND policyname='qc_issues_admin_all') THEN
    CREATE POLICY qc_issues_admin_all ON public.qc_issues FOR ALL TO authenticated
      USING (public.is_admin_or_va(auth.uid())) WITH CHECK (public.is_admin_or_va(auth.uid()));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='qc_issues' AND policyname='qc_issues_service_role') THEN
    CREATE POLICY qc_issues_service_role ON public.qc_issues FOR ALL TO service_role USING (true) WITH CHECK (true);
  END IF;
END$$;

-- ─── 3. qc_issue_events — full audit trail (who / what / when) ───────────────
