-- ─── updated_at triggers ─────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.va_perf_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'va_eod_submissions','va_verified_metrics','va_discrepancy_flags',
    'va_kpi_targets','va_performance_periods','va_coaching_log'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%s_touch ON public.%I', t, t);
    EXECUTE format(
      'CREATE TRIGGER trg_%s_touch BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.va_perf_touch_updated_at()',
      t, t
    );
  END LOOP;
END $$;

-- ─── RLS ─────────────────────────────────────────────────────────────────────
--
-- Read access is ADMIN-ONLY, deliberately. Qualitative fields (blockers, notes,
-- escalations) only stay safe to be honest in if they aren't visible to peers,
-- and the VA Performance tab is an admin surface. VAs reach their OWN day
-- exclusively through /api/va/eod, which verifies identity and then uses the
-- service role scoped to that one row.

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'va_eod_submissions','va_verified_metrics','va_discrepancy_flags',
    'va_kpi_targets','va_performance_periods','va_coaching_log'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_admin_all', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (public.has_role(auth.uid(), ''admin'')) WITH CHECK (public.has_role(auth.uid(), ''admin''))',
      t || '_admin_all', t
    );
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_service_role', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO service_role USING (true) WITH CHECK (true)',
      t || '_service_role', t
    );
  END LOOP;
END $$;

-- va_verified_metrics is system-written: strip UPDATE/INSERT from the admin
-- policy so nobody can hand-edit the source of truth from the console.
DROP POLICY IF EXISTS va_verified_metrics_admin_all ON public.va_verified_metrics;
DROP POLICY IF EXISTS va_verified_metrics_admin_read ON public.va_verified_metrics;
CREATE POLICY va_verified_metrics_admin_read ON public.va_verified_metrics
  FOR SELECT TO authenticated
  USING (public.has_role(auth.uid(), 'admin'));

