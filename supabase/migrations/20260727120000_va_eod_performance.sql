-- ─── VA EOD reporting + performance tracking with a verification layer ───────
--
-- The design inverts the usual self-reported EOD. The system pre-fills what it
-- already observed (Apploye hours, GHL activity, Airtable jobs/applicants,
-- workspace screening/onboarding, Stripe collections) and the VA only supplies
-- what no source can see. Three tiers of field:
--
--   Tier 1  auto-filled, read-only  — system-fed, a VA can never overwrite it
--   Tier 2  VA-entered, corroborated — compared to a signal on submit
--   Tier 3  qualitative, never scored — blockers, notes, priorities
--
-- Principles enforced by this schema:
--   * va_verified_metrics is SYSTEM-WRITTEN ONLY. Every metric column is
--     NULLABLE and NULL means "unverified" — a source outage must never be
--     recorded as a real zero.
--   * Every metric carries its source + sync timestamp (metric_sources) and
--     every source carries its reachability (source_status).
--   * Re-syncing a day updates in place (unique on va_id + work_date), so a
--     replay can never duplicate a day.
--   * One EOD submission per VA per day (unique on va_id + work_date).
--   * Discrepancies are prompts for human review, never penalties. A flag
--     captures the VA's explanation first; an admin decides the outcome.
--   * Apploye supplies HOURS ONLY. There is deliberately no column anywhere in
--     this schema for screenshots, activity percentages, keystrokes or app
--     usage — that data is never ingested, stored or displayed.
--
-- Reuses: va_onboarding (the VA record), events + discord_routes (alerts),
-- app_settings (thresholds + EOD window), pg_cron + pg_net (scheduled sync),
-- is_admin_or_va() / has_role() RLS.

-- ─── 1. VA record: verification identity + performance profile ───────────────
--
-- Metrics are attributed to a VA through their linked source user IDs. GHL and
-- workspace IDs already live on va_onboarding (ghl_user_id, portal_user_id);
-- Apploye is the only new one, and it reuses the column name and email-match
-- linking convention the cleaner side already established
-- (cleaners.apploye_member_id, see 20260530_apploye_integration.sql).

ALTER TABLE public.va_onboarding
  ADD COLUMN IF NOT EXISTS apploye_member_id text,
  ADD COLUMN IF NOT EXISTS start_date date,
  ADD COLUMN IF NOT EXISTS rate_cents integer,
  ADD COLUMN IF NOT EXISTS functions_assigned text[] NOT NULL DEFAULT '{}',
  -- Performance standing, distinct from the onboarding `status` lifecycle.
  ADD COLUMN IF NOT EXISTS performance_status text NOT NULL DEFAULT 'active',
  ADD COLUMN IF NOT EXISTS perf_airtable_record_id text;

DO $$
BEGIN
  ALTER TABLE public.va_onboarding
    ADD CONSTRAINT va_onboarding_performance_status_check
    CHECK (performance_status IN ('active','probation','inactive','removed'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE INDEX IF NOT EXISTS va_onboarding_apploye_idx
  ON public.va_onboarding (apploye_member_id) WHERE apploye_member_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS va_onboarding_portal_user_idx
  ON public.va_onboarding (portal_user_id) WHERE portal_user_id IS NOT NULL;

-- ─── 2. va_eod_submissions — one per VA per day ──────────────────────────────

CREATE TABLE IF NOT EXISTS public.va_eod_submissions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  submission_number integer GENERATED BY DEFAULT AS IDENTITY,
  va_id uuid NOT NULL REFERENCES public.va_onboarding(id) ON DELETE CASCADE,
  work_date date NOT NULL,

  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft','submitted','reviewed','flagged')),

  -- Which task blocks the VA opened. Drives which question sets rendered and
  -- therefore which Tier 2 fields are meaningful for this day.
  tasks_selected text[] NOT NULL DEFAULT '{}',

  -- Tier 2 ONLY: { metricKey: number }. Tier 1 values are never accepted from
  -- the client — they live exclusively on va_verified_metrics.
  self_reported jsonb NOT NULL DEFAULT '{}'::jsonb,

  -- Tier 3, never scored. Free text that is safe to be honest in.
  blockers text,
  priorities text,
  wins text,
  escalations text,
  task_notes jsonb NOT NULL DEFAULT '{}'::jsonb,   -- { taskId: note }

  -- Snapshot of the verified metrics the VA actually saw when submitting, so
  -- a later re-sync can never rewrite the history of what was reviewed.
  verified_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,

  submitted_at timestamptz,
  submitted_late boolean NOT NULL DEFAULT false,
  -- Once locked the day is read-only to the VA (admin window has passed).
  locked_at timestamptz,

  reviewed_by uuid,
  reviewed_by_name text,
  reviewed_at timestamptz,
  review_note text,

  airtable_record_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT va_eod_submissions_one_per_day UNIQUE (va_id, work_date)
);

CREATE INDEX IF NOT EXISTS va_eod_submissions_date_idx
  ON public.va_eod_submissions (work_date DESC);
CREATE INDEX IF NOT EXISTS va_eod_submissions_status_idx
  ON public.va_eod_submissions (status) WHERE status <> 'draft';

-- ─── 3. va_verified_metrics — the source of truth, system-written only ───────
--
-- NULL means UNVERIFIED (source unavailable / not configured / not applicable).
-- 0 means the source was reached and genuinely reported nothing. The two are
-- never conflated: source_status records reachability per source.

CREATE TABLE IF NOT EXISTS public.va_verified_metrics (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  va_id uuid NOT NULL REFERENCES public.va_onboarding(id) ON DELETE CASCADE,
  work_date date NOT NULL,

  -- Apploye (hours only — no activity, screenshots or app usage)
  hours_tracked numeric(6,2),

  -- GHL
  calls_placed integer,
  conversations_connected integer,
  sms_sent integer,
  inbound_leads integer,
  leads_responded integer,
  median_response_seconds integer,
  leads_converted integer,

  -- Airtable — Client & Revenue Ops / workspace bookings
  bookings_created integer,
  revenue_booked_cents bigint,
  quotes_sent integer,
  commercial_accounts_touched integer,
  walkthroughs_booked integer,

  -- Stripe
  revenue_collected_cents bigint,

  -- Airtable — Talent Acquisition / workspace cleaner hub
  applications_reviewed integer,
  phone_screens_completed integer,
  screens_advanced integer,
  screens_held integer,
  screens_declined integer,
  onboarding_launched integer,
  cleaners_activated integer,

  -- { source: { status: 'ok'|'unavailable'|'not_configured'|'unlinked',
  --             synced_at: iso, error?: string } }
  source_status jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- { metricKey: { source: string, synced_at: iso, status: string } }
  metric_sources jsonb NOT NULL DEFAULT '{}'::jsonb,

  last_synced_at timestamptz NOT NULL DEFAULT now(),
  airtable_record_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT va_verified_metrics_one_per_day UNIQUE (va_id, work_date)
);

CREATE INDEX IF NOT EXISTS va_verified_metrics_date_idx
  ON public.va_verified_metrics (work_date DESC);

COMMENT ON TABLE public.va_verified_metrics IS
  'System-written source of truth for VA daily metrics. Never hand-edited. NULL = unverified, never a real zero. Apploye contributes hours only — no activity or monitoring data is stored here or anywhere else.';

-- ─── 4. va_discrepancy_flags — a prompt to review, not an accusation ─────────

CREATE TABLE IF NOT EXISTS public.va_discrepancy_flags (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  flag_number integer GENERATED BY DEFAULT AS IDENTITY,
  va_id uuid NOT NULL REFERENCES public.va_onboarding(id) ON DELETE CASCADE,
  work_date date NOT NULL,
  submission_id uuid NOT NULL REFERENCES public.va_eod_submissions(id) ON DELETE CASCADE,

  metric_key text NOT NULL,
  metric_label text,
  self_reported numeric,
  verified numeric,
  variance numeric,
  variance_pct numeric,

  severity text NOT NULL DEFAULT 'low' CHECK (severity IN ('low','medium','high')),
  status text NOT NULL DEFAULT 'open'
    CHECK (status IN ('open','explained','confirmed_issue','dismissed')),

  -- The VA answers first. A human decides after.
  va_explanation text,
  va_explained_at timestamptz,

  review_note text,
  reviewed_by uuid,
  reviewed_by_name text,
  reviewed_at timestamptz,

  -- How many confirmed/open flags for this metric fell inside the rolling
  -- repeat window when this one was raised (drives High severity).
  repeat_count integer NOT NULL DEFAULT 0,

  airtable_record_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  -- Re-submitting the same day re-evaluates in place instead of piling up.
  CONSTRAINT va_discrepancy_flags_one_per_metric UNIQUE (submission_id, metric_key)
);

CREATE INDEX IF NOT EXISTS va_discrepancy_flags_open_idx
  ON public.va_discrepancy_flags (status, work_date DESC) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS va_discrepancy_flags_va_idx
  ON public.va_discrepancy_flags (va_id, work_date DESC);

COMMENT ON TABLE public.va_discrepancy_flags IS
  'Variance between a Tier 2 self-reported value and its corroborating signal. A flag asks for an explanation and routes to a human — it never auto-penalizes and never affects pay.';

