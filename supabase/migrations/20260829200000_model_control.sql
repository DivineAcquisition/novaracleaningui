-- Retention: the log is an audit trail, not a data warehouse. A year is well
-- past any dispute window that would need it.
CREATE OR REPLACE FUNCTION public.purge_ai_model_invocations()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_deleted integer;
BEGIN
  DELETE FROM public.ai_model_invocations
   WHERE created_at < now() - interval '365 days';
  GET DIAGNOSTICS v_deleted = ROW_COUNT;
  RETURN v_deleted;
END;
$$;

DO $$
DECLARE
  v_job_id bigint;
BEGIN
  SELECT jobid INTO v_job_id FROM cron.job WHERE jobname = 'ai-model-invocations-purge';
  IF v_job_id IS NOT NULL THEN PERFORM cron.unschedule('ai-model-invocations-purge'); END IF;
  PERFORM cron.schedule(
    'ai-model-invocations-purge',
    '30 4 * * 0',
    $cron$ SELECT public.purge_ai_model_invocations(); $cron$
  );
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'Skipping ai-model-invocations-purge cron schedule: %', SQLERRM;
END $$;

